USE ROLE ACCOUNTADMIN;

CREATE DATABASE IF NOT EXISTS ADVENTUREWORKS_DE;

CREATE SCHEMA IF NOT EXISTS ADVENTUREWORKS_DE.LANDING;
CREATE SCHEMA IF NOT EXISTS ADVENTUREWORKS_DE.RAW;
CREATE SCHEMA IF NOT EXISTS ADVENTUREWORKS_DE.DEV;
CREATE SCHEMA IF NOT EXISTS ADVENTUREWORKS_DE.DEV_SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS ADVENTUREWORKS_DE.SNAPSHOTS;
CREATE SCHEMA IF NOT EXISTS ADVENTUREWORKS_DE.PROD;
CREATE SCHEMA IF NOT EXISTS ADVENTUREWORKS_DE.DBT_PROJECTS;
CREATE SCHEMA IF NOT EXISTS ADVENTUREWORKS_DE.DBT_PROJECTS_CI;

CREATE WAREHOUSE IF NOT EXISTS INGEST_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE WAREHOUSE IF NOT EXISTS TRANSFORM_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE ROLE IF NOT EXISTS AW_INGEST_ROLE;
CREATE ROLE IF NOT EXISTS AW_DBT_DEVELOPER;
CREATE ROLE IF NOT EXISTS AW_DBT_PROD;
CREATE ROLE IF NOT EXISTS AW_BI_READER;
CREATE ROLE IF NOT EXISTS AW_CI_ROLE;
CREATE ROLE IF NOT EXISTS AW_CD_ROLE;

GRANT ROLE AW_INGEST_ROLE TO ROLE SYSADMIN;
GRANT ROLE AW_DBT_DEVELOPER TO ROLE SYSADMIN;
GRANT ROLE AW_DBT_PROD TO ROLE SYSADMIN;
GRANT ROLE AW_BI_READER TO ROLE SYSADMIN;
GRANT ROLE AW_CI_ROLE TO ROLE SYSADMIN;
GRANT ROLE AW_CD_ROLE TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE INGEST_WH TO ROLE AW_INGEST_ROLE;
GRANT USAGE ON DATABASE ADVENTUREWORKS_DE TO ROLE AW_INGEST_ROLE;
GRANT USAGE, CREATE FILE FORMAT, CREATE STAGE, CREATE PIPE
  ON SCHEMA ADVENTUREWORKS_DE.LANDING TO ROLE AW_INGEST_ROLE;
GRANT USAGE, CREATE TABLE ON SCHEMA ADVENTUREWORKS_DE.RAW
  TO ROLE AW_INGEST_ROLE;

GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE AW_DBT_DEVELOPER;
GRANT USAGE ON DATABASE ADVENTUREWORKS_DE TO ROLE AW_DBT_DEVELOPER;
GRANT USAGE ON SCHEMA ADVENTUREWORKS_DE.RAW TO ROLE AW_DBT_DEVELOPER;
GRANT SELECT ON ALL TABLES IN SCHEMA ADVENTUREWORKS_DE.RAW
  TO ROLE AW_DBT_DEVELOPER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ADVENTUREWORKS_DE.RAW
  TO ROLE AW_DBT_DEVELOPER;
GRANT USAGE, CREATE TABLE, CREATE VIEW
  ON SCHEMA ADVENTUREWORKS_DE.DEV TO ROLE AW_DBT_DEVELOPER;
GRANT USAGE, CREATE TABLE, CREATE VIEW
  ON SCHEMA ADVENTUREWORKS_DE.DEV_SNAPSHOTS TO ROLE AW_DBT_DEVELOPER;

GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE AW_DBT_PROD;
GRANT USAGE ON DATABASE ADVENTUREWORKS_DE TO ROLE AW_DBT_PROD;
GRANT USAGE ON SCHEMA ADVENTUREWORKS_DE.RAW TO ROLE AW_DBT_PROD;
GRANT SELECT ON ALL TABLES IN SCHEMA ADVENTUREWORKS_DE.RAW
  TO ROLE AW_DBT_PROD;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ADVENTUREWORKS_DE.RAW
  TO ROLE AW_DBT_PROD;
GRANT USAGE, CREATE TABLE, CREATE VIEW
  ON SCHEMA ADVENTUREWORKS_DE.PROD TO ROLE AW_DBT_PROD;
GRANT USAGE, CREATE TABLE, CREATE VIEW
  ON SCHEMA ADVENTUREWORKS_DE.SNAPSHOTS TO ROLE AW_DBT_PROD;

GRANT USAGE ON DATABASE ADVENTUREWORKS_DE TO ROLE AW_BI_READER;
GRANT USAGE ON SCHEMA ADVENTUREWORKS_DE.PROD TO ROLE AW_BI_READER;
GRANT SELECT ON ALL TABLES IN SCHEMA ADVENTUREWORKS_DE.PROD
  TO ROLE AW_BI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ADVENTUREWORKS_DE.PROD
  TO ROLE AW_BI_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA ADVENTUREWORKS_DE.PROD
  TO ROLE AW_BI_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ADVENTUREWORKS_DE.PROD
  TO ROLE AW_BI_READER;

GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE AW_CI_ROLE;
GRANT USAGE ON DATABASE ADVENTUREWORKS_DE TO ROLE AW_CI_ROLE;
GRANT USAGE ON SCHEMA ADVENTUREWORKS_DE.DBT_PROJECTS_CI TO ROLE AW_CI_ROLE;
GRANT CREATE DBT PROJECT ON SCHEMA ADVENTUREWORKS_DE.DBT_PROJECTS_CI
  TO ROLE AW_CI_ROLE;
GRANT ROLE AW_DBT_DEVELOPER TO ROLE AW_CI_ROLE;

GRANT USAGE ON WAREHOUSE TRANSFORM_WH TO ROLE AW_CD_ROLE;
GRANT USAGE ON DATABASE ADVENTUREWORKS_DE TO ROLE AW_CD_ROLE;
GRANT USAGE ON SCHEMA ADVENTUREWORKS_DE.DBT_PROJECTS TO ROLE AW_CD_ROLE;
GRANT CREATE DBT PROJECT ON SCHEMA ADVENTUREWORKS_DE.DBT_PROJECTS
  TO ROLE AW_CD_ROLE;
GRANT CREATE TASK ON SCHEMA ADVENTUREWORKS_DE.DBT_PROJECTS TO ROLE AW_CD_ROLE;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE AW_CD_ROLE;
GRANT ROLE AW_DBT_PROD TO ROLE AW_CD_ROLE;
GRANT ROLE AW_INGEST_ROLE TO ROLE AW_CD_ROLE;
