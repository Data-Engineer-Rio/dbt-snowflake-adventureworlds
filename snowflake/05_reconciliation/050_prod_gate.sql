USE ROLE AW_CD_ROLE;

EXECUTE IMMEDIATE $$
DECLARE
  RECONCILIATION_FAILED EXCEPTION (
    -20001,
    'Production reconciliation failed'
  );
  FAILURE_COUNT INTEGER;
BEGIN
  SELECT COUNT(*)
    INTO :FAILURE_COUNT
  FROM ADVENTUREWORKS_DE.PROD.AUDIT_RECONCILIATION_SUMMARY
  WHERE status = 'FAIL';

  IF (FAILURE_COUNT > 0) THEN
    RAISE RECONCILIATION_FAILED;
  END IF;

  RETURN 'PASS';
END;
$$;
